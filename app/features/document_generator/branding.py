# Helper 10 : Marqueur invisible DOCX (via run text vide + run.bookmark)
# ══════════════════════════════════════════════════════════════


def apply_docx_invisible_marker(document, ctx: BrandingContext) -> bool:
    """Ajoute un marqueur audit invisible dans le DOCX.

    OOXML n'a pas de commentaire HTML natif. On utilise donc le champ
    `core_properties.comments` (déjà posé par `apply_docx_core_properties`)
    PLUS un Run avec texte vide custom XML pour traçabilité forensic.

    V1 : on triche en utilisant un Run avec un caractère zero-width-space
    + le marker en texte normal masqué (font size 1pt invisible). Pas
    parfait mais grep-able.

    Pour un vrai marker invisible OOXML, il faudrait poser un
    `<w:customXml>` element dans `docProps/custom.xml` (V2).

    Fail-safe absolu : exception → log warning + return False.

    Args:
        document: Instance `docx.Document` mutée in-place.
        ctx: BrandingContext.

    Returns:
        True si appliqué avec succès, False sinon.
    """
    try:
        from docx.shared import Pt, RGBColor

        # On ajoute un paragraphe en fin de doc avec marker en taille 1pt
        # (invisible au rendu mais grep-able sur le fichier source XML).
        marker_text = (
            f"NEXYA-DOC-BRANDING version={ctx.version} "
            f"template={ctx.template} "
            f"generated_at={ctx.generated_at.isoformat()}"
        )
        p = document.add_paragraph()
        run = p.add_run(marker_text)
        run.font.size = Pt(1)
        run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)  # blanc sur blanc

        log.debug("documents.branding.docx_invisible_marker_applied")
        return True
    except Exception as exc:  # noqa: BLE001 — fail-safe absolu
        log.warning(
            "documents.branding.docx_invisible_marker_failed",
            error=str(exc),
            error_type=type(exc).__name__,
        )
        return False


