# Helper 7 : Header DOCX (python-docx section.header)
# ══════════════════════════════════════════════════════════════


def apply_docx_branding_header(document, ctx: BrandingContext) -> bool:
    """Ajoute un header `[NEXYA AI]` discret dans le DOCX.

    Pose un Run aligné à gauche dans `section.header.paragraphs[0]` —
    s'applique à toutes les pages via inheritance python-docx par défaut.

    Style : 8pt italique gris (#888) — discret, non-intrusif.

    Cohabite avec :
    - Le watermark footer C4.7d (logo + texte right-aligned bas de page)
    - Le contenu body (header naturellement séparé)

    Fail-safe absolu : exception → log warning + return False. Le DOCX
    est retourné quand même au user SANS header branding.

    Args:
        document: Instance `docx.Document` mutée in-place.
        ctx: BrandingContext.

    Returns:
        True si appliqué avec succès, False sinon.
    """
    try:
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.shared import Pt, RGBColor

        section = document.sections[0]
        header = section.header
        paragraph = header.paragraphs[0]
        paragraph.alignment = WD_ALIGN_PARAGRAPH.LEFT

        run = paragraph.add_run(f"[{ctx.brand_name}]")
        run.italic = True
        run.font.size = Pt(8)
        run.font.color.rgb = RGBColor(0x88, 0x88, 0x88)

        log.debug("documents.branding.docx_header_applied")
        return True
    except Exception as exc:  # noqa: BLE001 — fail-safe absolu
        log.warning(
            "documents.branding.docx_header_failed",
            error=str(exc),
            error_type=type(exc).__name__,
        )
        return False


# ══════════════════════════════════════════════════════════════
# Helper 8 : Footer DOCX page counter (PAGE / NUMPAGES via OxmlElement)
# ══════════════════════════════════════════════════════════════


def enrich_docx_footer_with_branding(
    document, ctx: BrandingContext
) -> bool:
    """Enrichit le footer DOCX avec branding texte + page counter natif.

    À appeler APRÈS `_apply_docx_watermark_footer` C4.7d (qui pose le
    logo + texte « Généré par NEXYA AI » right-aligned). On AJOUTE :
    - Une seconde ligne de footer left-aligned : `Nexyalabs · {date}`
    - Un champ page counter natif Word `Page <PAGE> / <NUMPAGES>` center

    Note : on ajoute un nouveau paragraphe footer, sans toucher au
    paragraphe existant C4.7d (préservation stricte du watermark).

    Pattern OxmlElement (Word fields) :
        - <w:fldSimple w:instr="PAGE"/>      → numéro page courante
        - <w:fldSimple w:instr="NUMPAGES"/>  → total pages

    Fail-safe absolu : exception → log warning + return False.

    Args:
        document: Instance `docx.Document` mutée in-place.
        ctx: BrandingContext.

    Returns:
        True si enrichi avec succès, False sinon.
    """
    try:
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.oxml.ns import qn
        from docx.oxml import OxmlElement
        from docx.shared import Pt, RGBColor

        section = document.sections[0]
        footer = section.footer

        # Ligne 2 : Nexyalabs · date · AI notice (centrée)
        # On AJOUTE un nouveau paragraphe (le watermark C4.7d est sur
        # le paragraphe 0). On garde le logo C4.7d intact.
        p_branding = footer.add_paragraph()
        p_branding.alignment = WD_ALIGN_PARAGRAPH.CENTER

        run_text = p_branding.add_run(
            f"{ctx.brand_company} · {ctx.date_iso}"
        )
        run_text.font.size = Pt(7)
        run_text.font.color.rgb = RGBColor(0xAA, 0xAA, 0xAA)
        run_text.italic = True

        # Ligne 3 : Page counter natif Word (PAGE / NUMPAGES)
        p_pages = footer.add_paragraph()
        p_pages.alignment = WD_ALIGN_PARAGRAPH.CENTER

        # « Page » prefix
        run_prefix = p_pages.add_run("Page ")
        run_prefix.font.size = Pt(7)
        run_prefix.font.color.rgb = RGBColor(0xAA, 0xAA, 0xAA)

        # <w:fldSimple w:instr="PAGE"/>
        fld_page = OxmlElement("w:fldSimple")
        fld_page.set(qn("w:instr"), "PAGE")
        run_page = p_pages.add_run()
        run_page.font.size = Pt(7)
        run_page.font.color.rgb = RGBColor(0xAA, 0xAA, 0xAA)
        run_page._r.append(fld_page)

        # « / » separator
        run_sep = p_pages.add_run(" / ")
        run_sep.font.size = Pt(7)
        run_sep.font.color.rgb = RGBColor(0xAA, 0xAA, 0xAA)

        # <w:fldSimple w:instr="NUMPAGES"/>
        fld_numpages = OxmlElement("w:fldSimple")
        fld_numpages.set(qn("w:instr"), "NUMPAGES")
        run_numpages = p_pages.add_run()
        run_numpages.font.size = Pt(7)
        run_numpages.font.color.rgb = RGBColor(0xAA, 0xAA, 0xAA)
        run_numpages._r.append(fld_numpages)

        log.debug("documents.branding.docx_footer_enriched")
        return True
    except Exception as exc:  # noqa: BLE001 — fail-safe absolu
        log.warning(
            "documents.branding.docx_footer_enrich_failed",
            error=str(exc),
            error_type=type(exc).__name__,
        )
        return False


