# Helper 4 : Footer CSS PDF (WeasyPrint @bottom-center)
# ══════════════════════════════════════════════════════════════


def build_pdf_branding_footer_css(ctx: BrandingContext) -> str:
    """Produit le bloc CSS @page bottom-center du footer branding PDF.

    Format : `Généré par NEXYA AI · Nexyalabs · 2026-05-31 · Page X / Y`

    Injecté dans `_base.html` via `{% block branding_css %}`. Cohabite
    avec :
    - @bottom-right (page numbers existant côté templates enfants)
    - @bottom-left (mention template existant côté templates enfants)

    Le branding footer est SUPPLÉMENTAIRE et discret. Les templates
    enfants conservent leur own @bottom-* CSS — on n'override pas
    leurs page numbers.

    Args:
        ctx: BrandingContext.

    Returns:
        Bloc CSS prêt à concaténer dans `<style>`.
    """
    if ctx.locale == "fr":
        prefix = "Généré par"
    else:
        prefix = "Generated by"

    # Format compact : « Généré par NEXYA AI · Nexyalabs · 2026-05-31 »
    # Les page numbers (counter(page) / counter(pages)) restent gérés
    # par chaque template enfant dans son @bottom-right propre.
    return (
        "@page {\n"
        "    @bottom-center {\n"
        f"        content: '{prefix} {ctx.brand_name} \\00b7 "
        f"{ctx.brand_company} \\00b7 {ctx.date_iso}';\n"
        "        font-size: 7.5pt;\n"
        "        color: #aaaaaa;\n"
        "        font-style: italic;\n"
        "    }\n"
        "}\n"
    )


