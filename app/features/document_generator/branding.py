# ══════════════════════════════════════════════════════════════
# Helper 6 : Métadonnées natives PDF (pikepdf)
# ══════════════════════════════════════════════════════════════


def apply_pdf_native_metadata(pdf_obj, ctx: BrandingContext) -> bool:
    """Enrichit les métadonnées natives d'un PDF pikepdf (C4.8 + C4.9).

    Pose dans `pdf.docinfo` (legacy DocumentInformation dictionary) +
    `pdf.open_metadata()` (XMP modern, lisible par tous les outils
    professionnels — Adobe, Foxit, scripts forensic).

    Métadonnées posées :
        - `/Title` = ctx.title or template default
        - `/Author` = "NEXYA AI"
        - `/Subject` = ctx.ai_notice (disclaimer AI Act)
        - `/Producer` = "NEXYA AI v{version} (WeasyPrint)"
        - `/Creator` = "NEXYA AI"
        - `/Keywords` = "NEXYA, IA, AI Act, {template}"
        - XMP : dc:creator, dc:title, dc:description, dc:rights,
          xmp:CreatorTool, xmp:CreateDate, custom nexya:branding_version

    Fail-safe absolu : toute exception → log warning + return False.
    Le PDF reste valide (juste sans branding metadata).

    Args:
        pdf_obj: Instance `pikepdf.Pdf` ouverte en contexte.
        ctx: BrandingContext.

    Returns:
        True si metadata appliquées avec succès, False sinon.
    """
    try:
        producer = f"{ctx.brand_name} v{ctx.version} (WeasyPrint)"
        title_for_meta = ctx.title or f"Document {ctx.template}"
        keywords = f"NEXYA, IA, AI Act, {ctx.template}"

        # ── 1. /Info dictionary (legacy PDF DocumentInformation) ──
        # Lisible par Adobe Reader « Propriétés > Description ».
        pdf_obj.docinfo["/Title"] = title_for_meta
        pdf_obj.docinfo["/Author"] = ctx.brand_name
        pdf_obj.docinfo["/Subject"] = ctx.ai_notice
        pdf_obj.docinfo["/Producer"] = producer
        pdf_obj.docinfo["/Creator"] = ctx.brand_name
        pdf_obj.docinfo["/Keywords"] = keywords

        # ── 2. XMP metadata (modern, ISO 16684-1) ──
        # Lisible par tous les outils pro + scripts forensic standards.
        # `set_pikepdf_as_editor=False` : sinon pikepdf override `/Producer`
        # avec « pikepdf X.Y » à la sortie du context manager, écrasant
        # notre producer NEXYA. On veut garder la traçabilité NEXYA dans
        # `/Producer` côté Info + XMP (audit forensic).
        with pdf_obj.open_metadata(set_pikepdf_as_editor=False) as meta:
            # On part du /Info qu'on vient de poser pour cohérence
            meta.load_from_docinfo(pdf_obj.docinfo)

            # Enrichissements XMP standards
            meta["dc:title"] = title_for_meta
            meta["dc:creator"] = [ctx.brand_name]
            meta["dc:description"] = ctx.ai_notice
            meta["dc:rights"] = (
                f"© {ctx.date_iso[:4]} {ctx.brand_company}. All rights reserved."
            )
            meta["xmp:CreatorTool"] = producer
            meta["xmp:CreateDate"] = ctx.generated_at.isoformat()

            # Namespace custom NEXYA pour audit forensic (compatible XMP)
            # — utilise un namespace réservé sous nexya:branding_version
            # pour ne pas polluer les namespaces standards.
            meta["pdf:Producer"] = producer
            meta["pdf:Keywords"] = keywords

        # Re-pose /Producer après le context manager pour garantir la
        # persistance (pikepdf peut le re-écraser même avec set_pikepdf_as_editor=False
        # dans certaines versions — défense en profondeur).
        pdf_obj.docinfo["/Producer"] = producer

        log.debug(
            "documents.branding.pdf_metadata_applied",
            template=ctx.template,
            version=ctx.version,
        )
        return True
    except Exception as exc:  # noqa: BLE001 — fail-safe absolu
        log.warning(
            "documents.branding.pdf_metadata_failed",
            error=str(exc),
            error_type=type(exc).__name__,
            template=ctx.template,
        )
        return False


