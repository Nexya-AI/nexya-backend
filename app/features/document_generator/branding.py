def apply_docx_core_properties(document, ctx: BrandingContext) -> bool:
    """Pose les `core_properties` DOCX (C4.9 — pendant des XMP PDF).

    `document.core_properties` correspond au fichier `docProps/core.xml`
    dans le ZIP DOCX. Lisible par Word « Fichier > Informations », par
    LibreOffice « Fichier > Propriétés », et par tout script forensic
    qui ouvre le ZIP.

    Champs posés :
        - title       = ctx.title or template default
        - author      = "NEXYA AI"
        - last_modified_by = "NEXYA AI"
        - comments    = ai_notice (disclaimer AI Act)
        - subject     = "Document généré par IA"
        - keywords    = "NEXYA, IA, AI Act, {template}"
        - category    = ctx.template
        - created     = ctx.generated_at
        - modified    = ctx.generated_at

    Fail-safe absolu : exception → log warning + return False.

    Args:
        document: Instance `docx.Document` mutée in-place.
        ctx: BrandingContext.

    Returns:
        True si appliqué avec succès, False sinon.
    """
    try:
        cp = document.core_properties
        title_for_meta = ctx.title or f"Document {ctx.template}"

        cp.title = title_for_meta
        cp.author = ctx.brand_name
        cp.last_modified_by = ctx.brand_name
        cp.comments = ctx.ai_notice
        cp.subject = (
            "Document généré par IA"
            if ctx.locale == "fr"
            else "AI-generated document"
        )
        cp.keywords = f"NEXYA, IA, AI Act, {ctx.template}"
        cp.category = ctx.template
        cp.created = ctx.generated_at
        cp.modified = ctx.generated_at

        log.debug(
            "documents.branding.docx_core_properties_applied",
            template=ctx.template,
        )
        return True
    except Exception as exc:  # noqa: BLE001 — fail-safe absolu
        log.warning(
            "documents.branding.docx_core_properties_failed",
            error=str(exc),
            error_type=type(exc).__name__,
            template=ctx.template,
        )
        return False


