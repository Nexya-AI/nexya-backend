@dataclass(frozen=True, slots=True)
class BrandingContext:
    """Contexte de branding pré-calculé pour une requête `generate`.

    Construit par `build_branding_context()` UNE FOIS, puis propagé aux
    différents helpers (CSS, footer, metadata, filename, marker).

    Attributes:
        version: Version pack branding (`c48-v1`).
        brand_name: Nom marque (`NEXYA AI`).
        brand_company: Société (`Nexyalabs`).
        ai_notice: Disclaimer AI Act UE selon locale.
        template: Slug du template utilisé (`school`, `minimal`, etc.).
        title: Titre du document (peut être None si défaut par template).
        generated_at: ISO datetime UTC de la requête (figé pour cohérence
            metadata cross-canal — PDF info, XMP, DOCX core_properties,
            HTML marker doivent tous porter exactement la même date).
        date_iso: Date `YYYY-MM-DD` UTC dérivée de `generated_at`.
        locale: `'fr'` (V1) ou `'en'` (V2 si l'app passe locale user).
    """

    version: str
    brand_name: str
    brand_company: str
    ai_notice: str
    template: str
    title: str | None
    generated_at: datetime
    date_iso: str
    locale: Literal["fr", "en"]


# ══════════════════════════════════════════════════════════════
# Helper 1 : Construction du contexte (point d'entrée unique)
# ══════════════════════════════════════════════════════════════


def build_branding_context(
    *,
    template: DocumentTemplate,
    title: str | None,
    locale: Literal["fr", "en"] = "fr",
    now: datetime | None = None,
) -> BrandingContext:
    """Construit le contexte de branding pour une requête `generate`.

    Single source of truth — appelé UNE fois par `service.generate`,
    puis propagé via le `BrandingContext` à tous les helpers.

    Args:
        template: Slug template (school/minimal/sciences/legal/medicine).
        title: Titre du document (peut être None).
        locale: Locale du disclaimer AI Act (fr défaut, en pour V2).
        now: datetime UTC override (tests reproductibles). Défaut = NOW.

    Returns:
        BrandingContext frozen, prêt à être consommé.
    """
    actual_now = now if now is not None else datetime.now(timezone.utc)
    notice = (
        AI_TRANSPARENCY_NOTICE_FR
        if locale == "fr"
        else AI_TRANSPARENCY_NOTICE_EN
    )
    return BrandingContext(
        version=BRANDING_VERSION,
        brand_name=BRAND_NAME,
        brand_company=BRAND_COMPANY,
        ai_notice=notice,
        template=template,
        title=title,
        generated_at=actual_now,
        date_iso=actual_now.strftime("%Y-%m-%d"),
        locale=locale,
    )


