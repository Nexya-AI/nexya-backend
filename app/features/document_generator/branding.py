# Helper 2 : Filename intelligent
# ══════════════════════════════════════════════════════════════

_FILENAME_SAFE_PATTERN: Final[re.Pattern[str]] = re.compile(r"[^a-zA-Z0-9_\-]+")
"""Caractères autorisés dans un filename branding (alpha + - + _)."""


def _slugify(raw: str, max_len: int = 60) -> str:
    """Convertit une string en slug ASCII safe pour filename.

    Pipeline :
        1. Normalize NFKD → strip accents (é → e, ñ → n, …)
        2. Lowercase
        3. Remplace tout caractère non-[a-z0-9_-] par `-`
        4. Strip leading/trailing `-` ou `_`
        5. Cap à `max_len` chars
        6. Fallback `document` si vide

    Args:
        raw: String brute (titre user-controlled possible).
        max_len: Longueur max du slug (défaut 60).

    Returns:
        Slug ASCII safe pour filename FS (jamais vide).
    """
    if not raw:
        return "document"
    # NFKD = decompose les accents, on garde uniquement ASCII
    normalized = unicodedata.normalize("NFKD", raw)
    ascii_only = normalized.encode("ascii", errors="ignore").decode("ascii")
    lower = ascii_only.lower().strip()
    if not lower:
        return "document"
    slug = _FILENAME_SAFE_PATTERN.sub("-", lower)
    slug = slug.strip("-_")
    if not slug:
        return "document"
    return slug[:max_len]


def generate_intelligent_filename(
    ctx: BrandingContext,
    *,
    extension: Literal["pdf", "docx"],
) -> str:
    """Génère un filename intelligent NEXYA-branded.

    Format : `nexya_<template>_<title-slug>_<YYYY-MM-DD>.<ext>`

    Exemples :
        - `nexya_minimal_cours-photosynthese_2026-05-31.pdf`
        - `nexya_school_devoir-maths_2026-05-31.docx`
        - `nexya_medicine_diabete-type-2_2026-05-31.pdf`
        - `nexya_minimal_document_2026-05-31.pdf` (si title None)

    Args:
        ctx: BrandingContext (porte template + title + date_iso).
        extension: `pdf` ou `docx`.

    Returns:
        Filename FS-safe ≤ 100 chars total.
    """
    title_slug = _slugify(ctx.title or "document", max_len=50)
    template_slug = _slugify(ctx.template, max_len=20)
    return f"nexya_{template_slug}_{title_slug}_{ctx.date_iso}.{extension}"


