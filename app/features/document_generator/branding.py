    # Note: le contenu est échappé via Jinja2 |e côté template — ici
    # on assemble du CSS pur sans variable user-controlled (brand_name
    # et version sont constants module-level).
    return (
        "@page {\n"
        "    @top-left {\n"
        f"        content: '[{ctx.brand_name}]';\n"
        "        font-size: 7.5pt;\n"
        "        color: #aaaaaa;\n"
        "        font-style: italic;\n"
        "    }\n"
        "}\n"
    )


